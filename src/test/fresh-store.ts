import { vi } from 'vitest';

/**
 * Свежий экземпляр стора — ровно такой, каким его создаёт модуль.
 *
 * Зачем это нужно. В шести стор-тестах был один и тот же приём:
 *
 *   beforeEach(() => useStore.setState({ ...дефолты }));
 *   it('начальное состояние', () => expect(useStore.getState().x).toBe(дефолт));
 *
 * Тест проверял не инициализатор стора, а строку, которую сам же в него
 * записал строкой выше. Поменяй в сторе дефолт на любой другой — тест
 * останется зелёным, потому что beforeEach перезапишет стор прежним
 * значением. Это не тест, это зеркало.
 *
 * `vi.resetModules()` сбрасывает реестр модулей, динамический импорт создаёт
 * стор заново — и проверка видит настоящий `create({...})`. Мутация дефолта
 * в сторе теперь краснит тест (см. пруфы в PR).
 *
 * @param load ленивый импорт конкретного экспорта, например
 *   `() => import('../app.store').then((m) => m.useAppStore)`
 */
export async function freshStore<T>(load: () => Promise<T>): Promise<T> {
  vi.resetModules();
  return load();
}
